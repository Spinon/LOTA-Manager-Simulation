import { writeFile } from 'node:fs/promises'
import path from 'node:path'

import { buildItemRuntimeAudit } from '../src/validation/itemRuntimeAudit.ts'

const audit = buildItemRuntimeAudit()
const outputDirectory = path.resolve(process.cwd(), 'tasks')
const jsonPath = path.join(outputDirectory, 'ITEM_RUNTIME_AUDIT.json')
const markdownPath = path.join(outputDirectory, 'ITEM_RUNTIME_AUDIT.md')

await writeFile(jsonPath, renderJson(audit), 'utf8')
await writeFile(markdownPath, renderMarkdown(audit), 'utf8')

console.log(`item runtime audit: ${audit.sourceItemCount} items and ${audit.effectCount} effects`)
console.log(`complete=${audit.statusCounts.complete} partial=${audit.statusCounts.partial} approximate=${audit.statusCounts.approximate} missing=${audit.statusCounts.missing}`)
console.log(`reports: ${path.relative(process.cwd(), markdownPath)}, ${path.relative(process.cwd(), jsonPath)}`)

function renderMarkdown(report) {
  const lines = [
    '# Item Runtime Audit',
    '',
    'Generated by `npm run audit:item-runtime`. The JSON file beside this report is the reviewed catalog baseline used by tests.',
    '',
    `- Source items: ${report.sourceItemCount}`,
    `- Source effects: ${report.effectCount}`,
    `- Buyable entries: ${report.buyableCount}`,
    `- Complete: ${report.statusCounts.complete}`,
    `- Partial: ${report.statusCounts.partial}`,
    `- Intentional approximation: ${report.statusCounts.approximate}`,
    `- Missing: ${report.statusCounts.missing}`,
    '',
    '## Runtime families',
    '',
    '| Family | Complete | Partial | Approximate | Missing |',
    '| --- | ---: | ---: | ---: | ---: |',
  ]

  Object.entries(report.familyCounts).forEach(([family, counts]) => {
    lines.push(`| ${family} | ${counts.complete} | ${counts.partial} | ${counts.approximate} | ${counts.missing} |`)
  })

  lines.push(
    '',
    '## Priority queue',
    '',
    'Items are ordered with missing support first, then partial support. The status is deliberately conservative: preserved source data is not considered implemented until a runtime path consumes it.',
    '',
    '| Item | Slot | Category | Status | Blocking families | Unhandled data |',
    '| --- | --- | --- | --- | --- | --- |',
  )

  report.rows
    .filter((row) => row.status === 'missing' || row.status === 'partial')
    .sort((left, right) => supportPriority(left.status) - supportPriority(right.status) || left.itemId.localeCompare(right.itemId))
    .forEach((row) => {
      const blockers = row.families
        .filter((family) => family.status === 'missing' || family.status === 'partial')
        .map((family) => `${family.id}:${family.status}`)
        .join(', ')
      const unhandled = [...row.unhandledStatKeys, ...row.unhandledEffectValueKeys].join(', ')
      lines.push(`| ${escapeCell(row.itemId)} | ${row.slot} | ${row.category} | ${row.status} | ${escapeCell(blockers)} | ${escapeCell(unhandled)} |`)
    })

  lines.push(
    '',
    '## Full matrix',
    '',
    'The complete evidence, tags, stat keys, value keys, and fingerprints are stored in `ITEM_RUNTIME_AUDIT.json`.',
    '',
    '| Item | Slot | Cost | Kinds | Status | Families |',
    '| --- | --- | ---: | --- | --- | --- |',
  )

  report.rows.forEach((row) => {
    const families = row.families.map((family) => `${family.id}:${family.status}`).join(', ')
    lines.push(`| ${escapeCell(row.itemId)} | ${row.slot} | ${row.cost} | ${row.effectKinds.join(', ')} | ${row.status} | ${escapeCell(families)} |`)
  })

  return `${lines.join('\n')}\n`
}

function renderJson(report) {
  return `${JSON.stringify(report, null, 2)}\n`
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|')
}

function supportPriority(status) {
  return status === 'missing' ? 0 : status === 'partial' ? 1 : 2
}
