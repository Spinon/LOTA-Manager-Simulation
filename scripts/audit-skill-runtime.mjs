import { writeFile } from 'node:fs/promises'
import path from 'node:path'

import { buildSkillRuntimeAudit } from '../src/validation/skillRuntimeAudit.ts'

const audit = buildSkillRuntimeAudit()
const outputDirectory = path.resolve(process.cwd(), 'tasks')
const jsonPath = path.join(outputDirectory, 'SKILL_RUNTIME_AUDIT.json')
const markdownPath = path.join(outputDirectory, 'SKILL_RUNTIME_AUDIT.md')

await writeFile(jsonPath, renderJson(audit), 'utf8')
await writeFile(markdownPath, renderMarkdown(audit), 'utf8')

console.log(`skill runtime audit: ${audit.skillCount} skills from ${audit.sourceHeroCount} heroes`)
console.log(`complete=${audit.statusCounts.complete} partial=${audit.statusCounts.partial} approximate=${audit.statusCounts.approximate} missing=${audit.statusCounts.missing}`)
console.log(`reports: ${path.relative(process.cwd(), markdownPath)}, ${path.relative(process.cwd(), jsonPath)}`)

function renderMarkdown(report) {
  const lines = [
    '# Skill Runtime Audit',
    '',
    'Generated by `npm run audit:skill-runtime`. The JSON file beside this report is the reviewed catalog baseline used by tests.',
    '',
    `- Source heroes: ${report.sourceHeroCount}`,
    `- Official skills: ${report.skillCount}`,
    `- Complete: ${report.statusCounts.complete}`,
    `- Partial: ${report.statusCounts.partial}`,
    `- Intentional approximation: ${report.statusCounts.approximate}`,
    `- Missing: ${report.statusCounts.missing}`,
    '',
    '## Runtime families',
    '',
    '| Family | Complete | Partial | Approximate | Missing |',
    '| --- | ---: | ---: | ---: | ---: |',
  ]

  Object.entries(report.familyCounts).forEach(([family, counts]) => {
    lines.push(`| ${family} | ${counts.complete} | ${counts.partial} | ${counts.approximate} | ${counts.missing} |`)
  })

  lines.push(
    '',
    '## Priority queue',
    '',
    'Skills are ordered with missing support first, then partial support. Supplemental skills remain missing until their unlock path is connected to the runtime selector.',
    '',
    '| Hero | Skill | Slot | Category | Status | Blocking families |',
    '| --- | --- | --- | --- | --- | --- |',
  )

  report.rows
    .filter((row) => row.status === 'missing' || row.status === 'partial')
    .sort((a, b) => supportPriority(a.status) - supportPriority(b.status) || a.heroId.localeCompare(b.heroId) || a.skillId.localeCompare(b.skillId))
    .slice(0, 160)
    .forEach((row) => {
      const blockers = row.families
        .filter((family) => family.status === 'missing' || family.status === 'partial')
        .map((family) => `${family.id}:${family.status}`)
        .join(', ')
      lines.push(`| ${escapeCell(row.heroId)} | ${escapeCell(row.skillId)} | ${row.key} | ${row.category} | ${row.status} | ${escapeCell(blockers)} |`)
    })

  lines.push(
    '',
    '## Full matrix',
    '',
    'The complete unabridged tag and value-key arrays are stored in `SKILL_RUNTIME_AUDIT.json`.',
    '',
    '| Hero | Skill | Slot | Runtime set | Kind/target | Status | Families |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  )

  report.rows.forEach((row) => {
    const families = row.families.map((family) => `${family.id}:${family.status}`).join(', ')
    lines.push(`| ${escapeCell(row.heroId)} | ${escapeCell(row.skillId)} | ${row.key} | ${row.runtimeSet} | ${row.kind}/${row.target} | ${row.status} | ${escapeCell(families)} |`)
  })

  return `${lines.join('\n')}\n`
}

function renderJson(report) {
  return [
    '{',
    `  "schemaVersion": ${report.schemaVersion},`,
    `  "sourceHeroCount": ${report.sourceHeroCount},`,
    `  "skillCount": ${report.skillCount},`,
    `  "statusCounts": ${JSON.stringify(report.statusCounts)},`,
    `  "familyCounts": ${JSON.stringify(report.familyCounts)},`,
    '  "rows": [',
    report.rows.map((row) => `    ${JSON.stringify(row)}`).join(',\n'),
    '  ]',
    '}',
    '',
  ].join('\n')
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|')
}

function supportPriority(status) {
  return status === 'missing' ? 0 : status === 'partial' ? 1 : 2
}
